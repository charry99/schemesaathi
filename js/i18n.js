// Current language: 'en' or 'te'. Persisted in localStorage.
function getLang() {
  const v = typeof localStorage !== 'undefined' ? localStorage.getItem('schemesaathi.lang') : null;
  return v === 'te' ? 'te' : 'en';
}

function setLang(code) {
  localStorage.setItem('schemesaathi.lang', code === 'te' ? 'te' : 'en');
}

// Look up a UI string for the current language, falling back to English.
function t(key) {
  const lang = getLang();
  return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
}

// Like t(), but fills {placeholders} from params, e.g. tr('rLevelOk', { level: 'UG' }).
function tr(key, params) {
  const s = t(key);
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, function (m, k) {
    return Object.prototype.hasOwnProperty.call(params, k) ? String(params[k]) : m;
  });
}

// Translate a data value (level, course, category, group, district) for the current language.
// English returns the value unchanged.
function tv(value) {
  if (getLang() !== 'te') return value;
  return Object.prototype.hasOwnProperty.call(VALUE_LABELS_TE, value) ? VALUE_LABELS_TE[value] : value;
}

// Translate and join a list of data values.
function tvList(values) {
  return (values || []).map(tv).join(', ');
}

